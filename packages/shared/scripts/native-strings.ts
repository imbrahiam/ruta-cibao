/**
 * Spanish catalogue -> Android resources, iOS String Catalog and Swift accessors.
 *
 *   packages/shared/messages/es.json
 *     -> apps/android/src/main/res/values/strings.xml
 *     -> apps/ios/Resources/Localizable.xcstrings
 *     -> apps/ios/Sources/Generated/Strings.swift
 *
 * Run: bun run packages/shared/scripts/native-strings.ts
 *
 * Supported ICU: `{arg}`, `{arg, plural, =0 one other}` with `#`,
 * `{arg, select, ...}` and rich-text tags (stripped, inner text kept).
 * Anything else throws, so a new construct never ships silently wrong.
 *
 * Messages with several top-level plural/select blocks (`explore.duration`)
 * are split into one resource per block, `<key>.<arg>`; the literal text
 * between the blocks is dropped and the caller joins the parts.
 */
