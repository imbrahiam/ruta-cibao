// ---- ICU parsing ----------------------------------------------------------

type Node =
  | { t: "text"; v: string }
  | { t: "arg"; name: string }
  | { t: "pound" }
  | { t: "plural"; name: string; opts: Record<string, Node[]> }
  | { t: "select"; name: string; opts: Record<string, Node[]> };

function parse(src: string, where: string, inPlural = false): Node[] {
  let i = 0;
  const fail = (msg: string): never => {
    throw new Error(`${where}: ${msg} in ${JSON.stringify(src)}`);
  };

  function nodes(stop: boolean, plural: boolean): Node[] {
    const out: Node[] = [];
    let text = "";
    const flush = () => {
      if (text) out.push({ t: "text", v: text });
      text = "";
    };
    while (i < src.length) {
      const c = src[i];
      if (c === "}" && stop) break;
      if (c === "{") {
        flush();
        i++;
        out.push(block());
        continue;
      }
      if (c === "<") {
        // Rich-text tag: drop the tag, keep the inner text.
        const m = /^<\/?[a-zA-Z][\w-]*\s*\/?>/.exec(src.slice(i));
        if (m) {
          i += m[0].length;
          continue;
        }
      }
      if (c === "#" && plural) {
        flush();
        out.push({ t: "pound" });
        i++;
        continue;
      }
      text += c;
      i++;
    }
    flush();
    return out;
  }

  function ident(): string {
    const m = /^\s*([A-Za-z_]\w*)\s*/.exec(src.slice(i));
    if (!m?.[1]) return fail("expected an argument name");
    i += m[0].length;
    return m[1];
  }

  function block(): Node {
    const name = ident();
    if (src[i] === "}") {
      i++;
      return { t: "arg", name };
    }
    if (src[i] !== ",") fail("expected ',' or '}'");
    i++;
    const kind = ident();
    if (kind !== "plural" && kind !== "select") {
      return fail(`unsupported ICU type "${kind}"`);
    }
    if (src[i] !== ",") fail("expected ','");
    i++;
    const opts: Record<string, Node[]> = {};
    for (;;) {
      while (/\s/.test(src[i] ?? "")) i++;
      if (src[i] === "}") {
        i++;
        break;
      }
      const m = /^(=\d+|[A-Za-z_]\w*)\s*\{/.exec(src.slice(i));
      if (!m?.[1]) return fail("expected a branch");
      i += m[0].length;
      opts[m[1]] = nodes(true, kind === "plural");
      if (src[i] !== "}") fail("unterminated branch");
      i++;
    }
    if (!opts.other) fail('missing "other" branch');
    return { t: kind, name, opts };
  }

  const result = nodes(false, inPlural);
  if (i < src.length) fail("unbalanced braces");
  return result;
}

// ---- Resource model ---------------------------------------------------------

/** One flat message: literal pieces, arguments and the plural `#`. */
type Template = Node[];

type Entry =
  | { kind: "string"; key: string; tpl: Template }
  | {
      kind: "plural";
      key: string;
      arg: string;
      /** Keys are `zero`, `one`, `other`. */
      branches: Record<string, Template>;
    };

function collectArgs(tpl: Template, into: string[]) {
  for (const n of tpl) {
    if (n.t === "arg" && !into.includes(n.name)) into.push(n.name);
  }
}

function checkFlat(tpl: Template, key: string) {
  for (const n of tpl) {
    if (n.t === "plural" || n.t === "select") {
      throw new Error(`${key}: nested plural/select is not supported`);
    }
  }
}

function pluralBranches(
  n: Extract<Node, { t: "plural" }>,
  before: Node[],
  after: Node[],
  key: string,
): Entry {
  const branches: Record<string, Template> = {};
  for (const [name, body] of Object.entries(n.opts)) {
    const cat = name === "=0" ? "zero" : name;
    if (cat !== "zero" && cat !== "one" && cat !== "other") {
      throw new Error(`${key}: unsupported plural branch "${name}"`);
    }
    const tpl = [...before, ...body, ...after];
    checkFlat(tpl, key);
    branches[cat] = tpl;
  }
  return { kind: "plural", key, arg: n.name, branches };
}

function toEntries(key: string, src: string): Entry[] {
  const ast = parse(src, key);
  const blocks = ast.filter(
    (n): n is Extract<Node, { t: "plural" | "select" }> =>
      n.t === "plural" || n.t === "select",
  );
  if (blocks.length === 0) {
    checkFlat(ast, key);
    return [{ kind: "string", key, tpl: ast }];
  }
  const [first] = blocks;
  if (blocks.length === 1 && first) {
    const idx = ast.indexOf(first);
    const before = ast.slice(0, idx);
    const after = ast.slice(idx + 1);
    const b = first;
    if (b.t === "plural") return [pluralBranches(b, before, after, key)];
    if (b.t !== "select") return [];
    return Object.entries(b.opts).map(([branch, body]) => {
      const tpl = [...before, ...body, ...after];
      checkFlat(tpl, key);
      return { kind: "string", key: `${key}.${branch}`, tpl } as Entry;
    });
  }
  // Several blocks: one resource per block, joined text dropped.
  return blocks.flatMap((b) => {
    if (b.t === "plural")
      return [pluralBranches(b, [], [], `${key}.${b.name}`)];
    if (b.t !== "select") return [];
    return Object.entries(b.opts).map(([branch, body]) => {
      checkFlat(body, key);
      return {
        kind: "string",
        key: `${key}.${b.name}.${branch}`,
        tpl: body,
      } as Entry;
    });
  });
}

function flatten(): { key: string; src: string }[] {
  const out: { key: string; src: string }[] = [];
  const catalogue = es as Record<string, unknown>;
  const walk = (path: string[], v: unknown) => {
    if (typeof v === "string") out.push({ key: path.join("."), src: v });
    else if (v && typeof v === "object") {
      for (const [k, x] of Object.entries(v)) walk([...path, k], x);
    } else throw new Error(`${path.join(".")}: not a string`);
  };
  for (const ns of NAMESPACES) {
    if (!(ns in catalogue)) throw new Error(`Unknown namespace "${ns}"`);
    walk([ns], catalogue[ns]);
  }
  return out;
}

// ---- Shared helpers -----------------------------------------------------------

/** Arguments of an entry in positional order: the plural count first. */
function entryArgs(e: Entry): { name: string; numeric: boolean }[] {
  const names: string[] = [];
  if (e.kind === "plural") names.push(e.arg);
  const tpls = e.kind === "string" ? [e.tpl] : Object.values(e.branches);
  for (const t of tpls) collectArgs(t, names);
  return names.map((name) => ({
    name,
    numeric: (e.kind === "plural" && name === e.arg) || NUMERIC_ARGS.has(name),
  }));
}

function tplHasArgs(tpl: Template): boolean {
  return tpl.some((n) => n.t === "arg" || n.t === "pound");
}

const snake = (s: string) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .toLowerCase();

const SWIFT_KEYWORDS = new Set(
  (
    "associatedtype class deinit enum extension fileprivate func import init inout internal let open " +
    "operator private precedencegroup protocol public rethrows static struct subscript typealias var " +
    "break case catch continue default defer do else fallthrough for guard if in repeat return throw " +
    "switch where while Any as await false is nil self Self super throws true try Type Protocol"
  ).split(" "),
);

function swiftId(s: string): string {
  let id = s.replace(/[^A-Za-z0-9_]/g, "_");
  if (/^\d/.test(id)) id = `_${id}`;
  return SWIFT_KEYWORDS.has(id) ? `\`${id}\`` : id;
}

const lowerFirst = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);
const upperFirst = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

/** `a.b.c` plus branch suffixes -> lowerCamel `aBC`-style leaf, from the last segment(s). */
function camel(parts: string[]): string {
  return parts
    .map((p, i) => (i === 0 ? lowerFirst(p) : upperFirst(p)))
    .join("");
}

// ---- Android ----------------------------------------------------------------------

function xmlText(s: string, formatted: boolean): string {
  let t = s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n");
  if (formatted) t = t.replace(/%/g, "%%");
  if (/^[@?]/.test(t)) t = `\\${t}`;
  return t;
}

function androidRender(
  tpl: Template,
  args: { name: string; numeric: boolean }[],
  pluralArg: string | null,
  formatted: boolean,
): string {
  const spec = (name: string) => {
    const idx = args.findIndex((a) => a.name === name);
    return `%${idx + 1}$${args[idx]?.numeric ? "d" : "s"}`;
  };
  return tpl
    .map((n) => {
      if (n.t === "text") return xmlText(n.v, formatted);
      if (n.t === "arg") return spec(n.name);
      if (n.t === "pound" && pluralArg) return spec(pluralArg);
      return "";
    })
    .join("");
}

function buildAndroid(entries: Entry[]): string {
  const names = new Map<string, string>();
  const claim = (name: string, key: string) => {
    const prev = names.get(name);
    if (prev)
      throw new Error(`Android name clash: ${prev} and ${key} -> ${name}`);
    names.set(name, key);
  };
  const o = [
    `<?xml version="1.0" encoding="utf-8"?>`,
    `<!-- ${HEADER} -->`,
    `<!-- Plural "=0" branches become a separate <name>_zero string: Spanish has no "zero" quantity on Android. -->`,
    "<resources>",
  ];
  for (const e of entries) {
    const base = snake(e.key);
    const args = entryArgs(e);
    if (e.kind === "string") {
      claim(base, e.key);
      const hasArgs = tplHasArgs(e.tpl);
      const text = androidRender(e.tpl, args, null, hasArgs);
      const attr = !hasArgs && text.includes("%") ? ` formatted="false"` : "";
      o.push(`    <string name="${base}"${attr}>${text}</string>`);
      continue;
    }
    claim(base, e.key);
    o.push(`    <plurals name="${base}">`);
    for (const q of ["one", "other"] as const) {
      const tpl = e.branches[q] ?? e.branches.other ?? [];
      o.push(
        `        <item quantity="${q}">${androidRender(tpl, args, e.arg, true)}</item>`,
      );
    }
    o.push("    </plurals>");
    if (e.branches.zero) {
      claim(`${base}_zero`, `${e.key} (zero)`);
      const hasArgs = tplHasArgs(e.branches.zero);
      o.push(
        `    <string name="${base}_zero">${androidRender(e.branches.zero, args, e.arg, hasArgs)}</string>`,
      );
    }
  }
  o.push("</resources>", "");
  return o.join("\n");
}

// ---- iOS ----------------------------------------------------------------------------

function iosRender(
  tpl: Template,
  args: { name: string; numeric: boolean }[],
  pluralArg: string | null,
  formatted: boolean,
): string {
  const spec = (name: string) => {
    const idx = args.findIndex((a) => a.name === name);
    return `%${idx + 1}$${args[idx]?.numeric ? "lld" : "@"}`;
  };
  return tpl
    .map((n) => {
      if (n.t === "text") return formatted ? n.v.replace(/%/g, "%%") : n.v;
      if (n.t === "arg") return spec(n.name);
      if (n.t === "pound" && pluralArg) return spec(pluralArg);
      return "";
    })
    .join("");
}

function buildXcstrings(entries: Entry[]): string {
  const strings: Record<string, unknown> = {};
  const unit = (value: string) => ({
    stringUnit: { state: "translated", value },
  });
  for (const e of entries) {
    const args = entryArgs(e);
    if (e.kind === "string") {
      const formatted = tplHasArgs(e.tpl);
      strings[e.key] = {
        extractionState: "manual",
        localizations: { es: unit(iosRender(e.tpl, args, null, formatted)) },
      };
      continue;
    }
    const plural: Record<string, unknown> = {};
    for (const q of ["zero", "one", "other"]) {
      const tpl = e.branches[q];
      if (tpl) plural[q] = unit(iosRender(tpl, args, e.arg, true));
    }
    // Plural variations need the one/other pair even if the source omits one.
    plural.one ??= plural.other;
    strings[e.key] = {
      extractionState: "manual",
      localizations: { es: { variations: { plural } } },
    };
  }
  const sorted: Record<string, unknown> = {};
  for (const k of Object.keys(strings).sort()) sorted[k] = strings[k];
  return `${JSON.stringify({ sourceLanguage: "es", strings: sorted, version: "1.0" }, null, 2)}\n`;
}

// ---- Swift accessors ---------------------------------------------------------------------

type Tree = { children: Map<string, Tree>; leaves: string[] };

function buildSwift(entries: Entry[]): string {
  const root: Tree = { children: new Map(), leaves: [] };
  for (const e of entries) {
    const parts = e.key.split(".");
    let node = root;
    for (const p of parts.slice(0, namespaceDepth(e.key))) {
      let next = node.children.get(p);
      if (!next) {
        next = { children: new Map(), leaves: [] };
        node.children.set(p, next);
      }
      node = next;
    }
    node.leaves.push(swiftMember(e, parts));
  }

  // A key that is both a leaf and a namespace would produce clashing names.
  const o = [`// ${HEADER}`, "", "import Foundation", "", "enum L10n {"];
  const emit = (tree: Tree, indent: string) => {
    for (const leaf of tree.leaves) {
      for (const line of leaf.split("\n")) o.push(line ? indent + line : "");
    }
    for (const [name, child] of tree.children) {
      if (tree.leaves.length || o[o.length - 1] !== "") o.push("");
      o.push(`${indent}enum ${swiftId(upperFirst(name))} {`);
      emit(child, `${indent}    `);
      o.push(`${indent}}`);
    }
  };
  emit(root, "    ");
  o.push("}", "");
  return o.join("\n").replace(/\n{3,}/g, "\n\n");
}

function swiftMember(e: Entry, parts: string[]): string {
  // `parts` is the full key path; the member lives in the enum of its parent.
  // Select/multi-block keys have extra trailing segments, flattened into the name.
  const name = swiftId(camel(parts.slice(namespaceDepth(e.key))));
  const args = entryArgs(e);
  const keyLit = JSON.stringify(e.key);
  if (args.length === 0) {
    return `static var ${name}: String { String(localized: LocalizedStringResource(${keyLit})) }`;
  }
  const params = args
    .map((a) => `${swiftId(a.name)}: ${a.numeric ? "Int" : "String"}`)
    .join(", ");
  const values = args.map((a) => swiftId(a.name)).join(", ");
  return [
    `static func ${name}(${params}) -> String {`,
    `    String.localizedStringWithFormat(`,
    `        NSLocalizedString(${keyLit}, comment: ""), ${values}`,
    `    )`,
    `}`,
  ].join("\n");
}

/**
 * Keys are `<ns>.<...path>`; leaf members sit in the enum of the last *catalogue*
 * path segment's parent. Branch/part suffixes (added by splitting) have no
 * catalogue counterpart and are folded into the member name.
 */
const catalogueDepths = new Map<string, number>();
function namespaceDepth(key: string): number {
  return catalogueDepths.get(key) ?? key.split(".").length - 1;
}

// ---- Main -------------------------------------------------------------------------------------

function write(path: string, content: string) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${path.replace(`${ROOT}/`, "")}`);
}

const entries: Entry[] = [];
for (const { key, src } of flatten()) {
  const depth = key.split(".").length - 1;
  for (const e of toEntries(key, src)) {
    catalogueDepths.set(e.key, depth);
    entries.push(e);
  }
}

write(ANDROID_OUT, buildAndroid(entries));
write(XCSTRINGS_OUT, buildXcstrings(entries));
write(SWIFT_OUT, buildSwift(entries));

// Server-sent messages (notifications) name a catalogue key at runtime, with
// named params. Native catalogues are positional, so emit each key's argument
// order for the platforms to format by key (`MessageArgs.swift` / `MessageArgs.kt`).
