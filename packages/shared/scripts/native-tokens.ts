type Rgba = { r: number; g: number; b: number; a: number };

function parseColor(value: string): Rgba {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex) {
    const n = Number.parseInt(hex[1] ?? "", 16);
    return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255, a: 1 };
  }
  const rgba =
    /^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/.exec(
      value,
    );
  if (rgba) {
    return {
      r: Number(rgba[1]),
      g: Number(rgba[2]),
      b: Number(rgba[3]),
      a: rgba[4] === undefined ? 1 : Number(rgba[4]),
    };
  }
  throw new Error(`Unsupported colour: ${value}`);
}

const byte = (n: number) => n.toString(16).toUpperCase().padStart(2, "0");

function swiftColor(value: string): string {
  const c = parseColor(value);
  const hex = `0x${byte(c.r)}${byte(c.g)}${byte(c.b)}`;
  return c.a === 1 ? `rgb(${hex})` : `rgb(${hex}, ${c.a})`;
}

function kotlinColor(value: string): string {
  const c = parseColor(value);
  const alpha = Math.round(c.a * 255);
  return `Color(0x${byte(alpha)}${byte(c.r)}${byte(c.g)}${byte(c.b)})`;
}

const themeIds = Object.keys(THEMES) as (keyof typeof THEMES)[];
const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

const samplePalette = buildPalette(THEMES[DEFAULT_THEME].light, "light");
const paletteKeys = Object.keys(
  samplePalette,
) as (keyof typeof samplePalette)[];
const mapKeys = Object.keys(THEMES[DEFAULT_THEME].map.light);
const typeKeys = Object.keys(type) as (keyof typeof type)[];
const spaceKeys = Object.keys(space) as (keyof typeof space)[];
const radiusKeys = Object.keys(radius) as (keyof typeof radius)[];
const easeKeys = Object.keys(ease) as (keyof typeof ease)[];
const springKeys = Object.keys(spring) as (keyof typeof spring)[];

/** Both schemes of every theme, in a stable order, as [theme, scheme, colours]. */
function* eachPalette() {
  for (const id of themeIds) {
    for (const scheme of ["light", "dark"] as const) {
      yield { id, scheme, theme: THEMES[id] };
    }
  }
}

function swiftWeight(w: string): string {
  const map: Record<string, string> = {
    "400": ".regular",
    "600": ".semibold",
    "700": ".bold",
  };
  const out = map[w];
  if (!out) throw new Error(`Unmapped font weight ${w}`);
  return out;
}

function kotlinWeight(w: string): string {
  const map: Record<string, string> = {
    "400": "FontWeight.Normal",
    "600": "FontWeight.SemiBold",
    "700": "FontWeight.Bold",
  };
  const out = map[w];
  if (!out) throw new Error(`Unmapped font weight ${w}`);
  return out;
}

function buildSwift(): string {
  const o: string[] = [];
  o.push(`// ${HEADER}`, "", "import SwiftUI", "");
  o.push("private func rgb(_ hex: UInt32, _ alpha: Double = 1) -> Color {");
  o.push("    Color(");
  o.push("        .sRGB,");
  o.push("        red: Double((hex >> 16) & 0xFF) / 255,");
  o.push("        green: Double((hex >> 8) & 0xFF) / 255,");
  o.push("        blue: Double(hex & 0xFF) / 255,");
  o.push("        opacity: alpha");
  o.push("    )");
  o.push("}", "");

  o.push("enum RutaTheme: String, CaseIterable {");
  for (const id of themeIds) o.push(`    case ${id}`);
  o.push("");
  o.push(`    static let \`default\`: RutaTheme = .${DEFAULT_THEME}`);
  o.push("}", "");

  o.push("struct RutaPalette {");
  for (const k of paletteKeys) o.push(`    let ${k}: Color`);
  o.push("}", "");

  o.push("struct RutaMapPalette {");
  for (const k of mapKeys) o.push(`    let ${k}: Color`);
  o.push("}", "");

  o.push("extension RutaPalette {");
  o.push(
    "    static func palette(_ theme: RutaTheme, _ scheme: ColorScheme) -> RutaPalette {",
  );
  o.push("        switch (theme, scheme) {");
  for (const { id, scheme, theme } of eachPalette()) {
    const p = buildPalette(theme[scheme], scheme);
    o.push(
      `        case (.${id}, ${scheme === "dark" ? ".dark" : ".light"}):`,
      "            return RutaPalette(",
    );
    paletteKeys.forEach((k, i) => {
      const comma = i === paletteKeys.length - 1 ? "" : ",";
      o.push(`                ${k}: ${swiftColor(p[k])}${comma}`);
    });
    o.push("            )");
  }
  o.push("        @unknown default:");
  o.push("            return palette(theme, .light)");
  o.push("        }", "    }", "");
  o.push(
    "    static func mapPalette(_ theme: RutaTheme, _ scheme: ColorScheme) -> RutaMapPalette {",
  );
  o.push("        switch (theme, scheme) {");
  for (const { id, scheme, theme } of eachPalette()) {
    const m = theme.map[scheme] as Record<string, string>;
    o.push(
      `        case (.${id}, ${scheme === "dark" ? ".dark" : ".light"}):`,
      "            return RutaMapPalette(",
    );
    mapKeys.forEach((k, i) => {
      const comma = i === mapKeys.length - 1 ? "" : ",";
      o.push(`                ${k}: ${swiftColor(m[k] ?? "")}${comma}`);
    });
    o.push("            )");
  }
  o.push("        @unknown default:");
  o.push("            return mapPalette(theme, .light)");
  o.push("        }", "    }", "}", "");

  o.push("/// Brand colours that do not change with the theme.");
  o.push("enum RutaBrand {");
  for (const [k, v] of Object.entries(BRAND_COLORS)) {
    o.push(`    static let ${k} = ${swiftColor(v)}`);
  }
  o.push("}", "");

  o.push("/// 4pt grid.", "enum RutaSpace {");
  for (const k of spaceKeys)
    o.push(`    static let ${k}: CGFloat = ${space[k]}`);
  o.push("}", "");

  o.push("enum RutaRadius {");
  for (const k of radiusKeys) {
    o.push(`    static let ${k}: CGFloat = ${radius[k]}`);
  }
  o.push("}", "");

  o.push("/// Minimum touch target in points.", "enum RutaTouch {");
  o.push(`    static let minimum: CGFloat = ${TOUCH.ios}`);
  o.push("}", "");

  o.push("struct RutaTextStyle {");
  o.push("    let size: CGFloat");
  o.push("    let lineHeight: CGFloat");
  o.push("    let weight: Font.Weight");
  o.push("    let tracking: CGFloat");
  o.push("}", "");
  o.push("enum RutaType {");
  for (const k of typeKeys) {
    const t = type[k];
    o.push(
      `    static let ${k} = RutaTextStyle(size: ${t.fontSize}, lineHeight: ${t.lineHeight}, weight: ${swiftWeight(t.fontWeight)}, tracking: ${t.letterSpacing})`,
    );
  }
  o.push("}", "");

  o.push(
    "/// Cubic bezier control points (x1, y1, x2, y2).",
    "enum RutaEase {",
  );
  for (const k of easeKeys) {
    o.push(
      `    static let ${k}: (Double, Double, Double, Double) = (${ease[k].join(", ")})`,
    );
  }
  o.push("}", "");

  o.push("struct RutaSpring {");
  o.push("    /// Seconds.", "    let duration: Double");
  o.push("    let dampingRatio: Double");
  o.push("}", "");
  o.push("enum RutaMotion {");
  for (const k of springKeys) {
    o.push(
      `    static let ${k} = RutaSpring(duration: ${spring[k].duration / 1000}, dampingRatio: ${spring[k].dampingRatio})`,
    );
  }
  o.push("}", "");
  return o.join("\n");
}

function buildKotlin(): string {
  const o: string[] = [];
  o.push(`// ${HEADER}`, "", "package rutacibao.android.generated", "");
  o.push(
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.text.font.FontWeight",
    "import androidx.compose.ui.unit.TextUnit",
    "import androidx.compose.ui.unit.dp",
    "import androidx.compose.ui.unit.sp",
    "",
  );
  o.push("enum class RutaTheme {");
  o.push(`    ${themeIds.map(pascal).join(", ")};`, "");
  o.push("    companion object {");
  o.push(`        val Default = ${pascal(DEFAULT_THEME)}`);
  o.push("    }", "}", "");

  o.push("data class RutaPalette(");
  paletteKeys.forEach((k, i) => {
    o.push(`    val ${k}: Color${i === paletteKeys.length - 1 ? "" : ","}`);
  });
  o.push(")", "");
  o.push("data class RutaMapPalette(");
  mapKeys.forEach((k, i) => {
    o.push(`    val ${k}: Color${i === mapKeys.length - 1 ? "" : ","}`);
  });
  o.push(")", "");

  o.push("fun rutaPalette(theme: RutaTheme, dark: Boolean): RutaPalette =");
  o.push("    when (theme) {");
  for (const id of themeIds) {
    o.push(`        RutaTheme.${pascal(id)} ->`);
    o.push("            if (dark) {");
    for (const scheme of ["dark", "light"] as const) {
      const p = buildPalette(THEMES[id][scheme], scheme);
      if (scheme === "light") o.push("            } else {");
      o.push("                RutaPalette(");
      paletteKeys.forEach((k, i) => {
        o.push(
          `                    ${k} = ${kotlinColor(p[k])}${i === paletteKeys.length - 1 ? "" : ","}`,
        );
      });
      o.push("                )");
    }
    o.push("            }");
  }
  o.push("    }", "");

  o.push(
    "fun rutaMapPalette(theme: RutaTheme, dark: Boolean): RutaMapPalette =",
  );
  o.push("    when (theme) {");
  for (const id of themeIds) {
    o.push(`        RutaTheme.${pascal(id)} ->`);
    o.push("            if (dark) {");
    for (const scheme of ["dark", "light"] as const) {
      const m = THEMES[id].map[scheme] as Record<string, string>;
      if (scheme === "light") o.push("            } else {");
      o.push("                RutaMapPalette(");
      mapKeys.forEach((k, i) => {
        o.push(
          `                    ${k} = ${kotlinColor(m[k] ?? "")}${i === mapKeys.length - 1 ? "" : ","}`,
        );
      });
      o.push("                )");
    }
    o.push("            }");
  }
  o.push("    }", "");

  o.push("/** Brand colours that do not change with the theme. */");
  o.push("object RutaBrand {");
  for (const [k, v] of Object.entries(BRAND_COLORS)) {
    o.push(`    val ${k} = ${kotlinColor(v)}`);
  }
  o.push("}", "");

  o.push("/** 4pt grid. */", "object RutaSpace {");
  for (const k of spaceKeys) o.push(`    val ${k} = ${space[k]}.dp`);
  o.push("}", "");
  o.push("object RutaRadius {");
  for (const k of radiusKeys) o.push(`    val ${k} = ${radius[k]}.dp`);
  o.push("}", "");
  o.push("/** Minimum touch target. */", "object RutaTouch {");
  o.push(`    val minimum = ${TOUCH.android}.dp`);
  o.push("}", "");

  o.push("data class RutaTextStyle(");
  o.push("    val fontSize: TextUnit,");
  o.push("    val lineHeight: TextUnit,");
  o.push("    val fontWeight: FontWeight,");
  o.push("    val letterSpacing: TextUnit,");
  o.push(")", "");
  o.push("object RutaType {");
  for (const k of typeKeys) {
    const t = type[k];
    o.push(
      `    val ${k} = RutaTextStyle(${t.fontSize}.sp, ${t.lineHeight}.sp, ${kotlinWeight(t.fontWeight)}, ${t.letterSpacing}.sp)`,
    );
  }
  o.push("}", "");

  o.push("/** Cubic bezier control points (x1, y1, x2, y2). */");
  o.push("object RutaEase {");
  for (const k of easeKeys) {
    o.push(
      `    val ${k} = floatArrayOf(${ease[k].map((n) => `${n}f`).join(", ")})`,
    );
  }
  o.push("}", "");
  o.push(
    "data class RutaSpring(val durationMillis: Int, val dampingRatio: Float)",
  );
  o.push("");
  o.push("object RutaMotion {");
  for (const k of springKeys) {
    o.push(
      `    val ${k} = RutaSpring(${spring[k].duration}, ${spring[k].dampingRatio}f)`,
    );
  }
  o.push("}", "");
  return o.join("\n");
}

function write(path: string, content: string) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${path.replace(`${ROOT}/`, "")}`);
}

write(SWIFT_OUT, buildSwift());
write(KOTLIN_OUT, buildKotlin());
