/**
 * Renders the category icon set (`src/ui/icon.tsx` CATEGORY_ICONS keys) to
 * white PNGs the map draws as SDF icons, tinted per layer. Lucide (ISC).
 *
 *   bun run apps/mobile/scripts/generate-map-glyphs.ts
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const NAMES = [
  "bed",
  "bed-double",
  "bike",
  "building-2",
  "bus",
  "car",
  "church",
  "cloud-rain",
  "coffee",
  "construction",
  "cross",
  "droplets",
  "fuel",
  "footprints",
  "graduation-cap",
  "hospital",
  "landmark",
  "leaf",
  "lightbulb",
  "map-pin",
  "mountain",
  "octagon-x",
  "pill",
  "route",
  "shopping-bag",
  "shopping-basket",
  "store",
  "tent",
  "trash-2",
  "trees",
  "triangle-alert",
  "utensils",
  "waves",
  "wheat",
  "wifi",
  "wrench",
];

const SOURCE = path.join(
  import.meta.dirname,
  "../../../node_modules/lucide-static/icons",
);
const OUT = path.join(import.meta.dirname, "../assets/map-glyphs");
const SIZE = 64;

await mkdir(OUT, { recursive: true });
const index: string[] = [];
for (const name of NAMES) {
  const svg = (await readFile(path.join(SOURCE, `${name}.svg`), "utf8"))
    .replace(/stroke="currentColor"/g, 'stroke="#FFFFFF"')
    .replace(/stroke-width="2"/g, 'stroke-width="2.4"');
  await sharp(Buffer.from(svg), { density: 600 })
    .resize(SIZE, SIZE)
    .png()
    .toFile(path.join(OUT, `${name}.png`));
  index.push(`  "${name}": require("../../../assets/map-glyphs/${name}.png"),`);
}

await writeFile(
  path.join(import.meta.dirname, "../src/features/map/glyphs.ts"),
  `// Generated by scripts/generate-map-glyphs.ts — do not edit.\n/** White category glyphs, drawn by the map as SDF icons. */\nexport const MAP_GLYPHS: Record<string, number> = {\n${index.join("\n")}\n};\n`,
);
console.log(`wrote ${NAMES.length} glyphs`);
