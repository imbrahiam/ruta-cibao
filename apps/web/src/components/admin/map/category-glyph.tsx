/**
 * Category icons are data: staff pick one in the categories desk and it is
 * stored by its Lucide name. Same set as the phone app's
 * `apps/mobile/src/ui/icon.tsx`; an unknown name falls back to a pin.
 */
const CATEGORY_ICONS: Record<string, LucideIcon> = {
  bed: Bed,
  "bed-double": BedDouble,
  bike: Bike,
  "building-2": Building2,
  bus: Bus,
  car: Car,
  church: Church,
  "cloud-rain": CloudRain,
  coffee: Coffee,
  construction: Construction,
  cross: Cross,
  droplets: Droplets,
  fuel: Fuel,
  footprints: Footprints,
  "graduation-cap": GraduationCap,
  hospital: Hospital,
  landmark: Landmark,
  leaf: Leaf,
  lightbulb: Lightbulb,
  "map-pin": MapPin,
  "messages-square": MessagesSquare,
  mountain: Mountain,
  "octagon-x": OctagonX,
  pill: Pill,
  route: Route,
  "shopping-bag": ShoppingBag,
  "shopping-basket": ShoppingBasket,
  store: Store,
  tent: Tent,
  "trash-2": Trash2,
  trees: Trees,
  "triangle-alert": TriangleAlert,
  utensils: Utensils,
  waves: Waves,
  wheat: Wheat,
  wifi: Wifi,
  wrench: Wrench,
};

export function categoryIcon(name: string | null | undefined): LucideIcon {
  return (name && CATEGORY_ICONS[name]) || MapPin;
}
