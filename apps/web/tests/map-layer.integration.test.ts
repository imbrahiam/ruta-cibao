import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { eq, inArray } from "drizzle-orm";
import { db } from "@/db";
import { categories, municipalities, places } from "@/db/schema";
import {
  CLUSTER_MAX_ZOOM,
  parseTileCoordinates,
  placesTile,
} from "@/lib/tiles";
import { readMunicipalBoundaries } from "@/modules/offline/snapshot";
import { assertDedicatedLocalDatabase } from "./support/test-db";

/**
 * The map is the product. Two things make it work without a third-party
 * basemap: the municipal outline the app draws and the vector tiles it
 * requests. Both are generated by PostGIS, so the promises live at the SQL
 * boundary — published only, clustered when zoomed out, and a real polygon
 * rather than an empty layer.
 */
describe.skipIf(process.env.RUN_DB_TESTS !== "1")("map layer", () => {
  const prefix = `map-${crypto.randomUUID().slice(0, 8)}`;
  const town = `${prefix}-town`;
  const categoryId = `${prefix}-category`;
  const publishedSlug = `${prefix}-published`;
  const pendingSlug = `${prefix}-pending`;
  const clusterOneSlug = `${prefix}-cluster-one`;
  const clusterTwoSlug = `${prefix}-cluster-two`;
  const lng = 10.005;
  const lat = 10.005;
  let guarded = false;

  function tile(lng: number, lat: number, z: number) {
    const n = 2 ** z;
    const x = Math.floor(((lng + 180) / 360) * n);
    const radians = (lat * Math.PI) / 180;
    const y = Math.floor(
      ((1 - Math.log(Math.tan(radians) + 1 / Math.cos(radians)) / Math.PI) /
        2) *
        n,
    );
    return { z, x, y };
  }

  beforeAll(async () => {
    assertDedicatedLocalDatabase();
    guarded = true;
    await db.insert(municipalities).values({
      id: town,
      name: "Synthetic map town",
      boundary: `SRID=4326;MULTIPOLYGON(((10 10,10.01 10,10.01 10.01,10 10.01,10 10)))`,
    });
    await db.insert(categories).values({
      id: categoryId,
      kind: "place",
      name: "Mapa",
      color: "#1d4ed8",
      icon: "map-pin",
    });
    await db.insert(places).values([
      {
        slug: publishedSlug,
        name: "Lugar publicado",
        categoryId,
        municipalityId: town,
        location: { x: lng, y: lat },
        status: "published",
      },
      {
        slug: pendingSlug,
        name: "Lugar pendiente",
        categoryId,
        municipalityId: town,
        location: { x: lng, y: lat },
        status: "pending",
      },
      {
        slug: clusterOneSlug,
        name: "Lugar agrupado uno",
        categoryId,
        municipalityId: town,
        location: { x: 20.005, y: 20.005 },
        status: "published",
      },
      {
        slug: clusterTwoSlug,
        name: "Lugar agrupado dos",
        categoryId,
        municipalityId: town,
        location: { x: 20.005, y: 20.005 },
        status: "published",
      },
    ]);
  });

  afterAll(async () => {
    if (!guarded) return;
    await db.delete(places).where(eq(places.municipalityId, town));
    await db.delete(categories).where(inArray(categories.id, [categoryId]));
    await db.delete(municipalities).where(eq(municipalities.id, town));
  });

  test("the municipal outline is a GeoJSON polygon with a label point", async () => {
    const boundaries = await readMunicipalBoundaries();
    const feature = boundaries.features.find((row) => row.id === town);

    expect(feature?.properties.name).toBe("Synthetic map town");
    const geometry = feature?.geometry as { type?: string } | undefined;
    expect(["Polygon", "MultiPolygon"]).toContain(geometry?.type ?? "");
    expect(feature?.properties.label).toHaveLength(2);
    expect(boundaries.province).not.toBeNull();
    expect(boundaries.outside).not.toBeNull();
  });

  test("a close zoom carries the published place and never the pending one", async () => {
    const body = await placesTile(tile(lng, lat, 14));
    const text = body.toString("latin1");

    expect(body.length).toBeGreaterThan(0);
    expect(text).toContain(publishedSlug);
    expect(text).not.toContain(pendingSlug);
  });

  test("a province-wide zoom clusters neighbours instead of drawing them", async () => {
    expect(CLUSTER_MAX_ZOOM).toBeLessThan(14);
    const body = await placesTile(tile(20.005, 20.005, 6));
    const text = body.toString("latin1");

    expect(body.length).toBeGreaterThan(0);
    expect(text).toContain("clusters");
    expect(text).not.toContain(clusterOneSlug);
    expect(text).not.toContain(clusterTwoSlug);
    expect(text).toContain("count");
  });

  test("an empty tile is an empty answer, not an error", async () => {
    const body = await placesTile(tile(0, 0, 14));
    expect(body.length).toBe(0);
  });

  test("coordinates outside the tile pyramid are refused before any query", () => {
    expect(parseTileCoordinates("14", "0", "0")).toEqual({ z: 14, x: 0, y: 0 });
    expect(parseTileCoordinates("21", "0", "0")).toBeNull();
    expect(parseTileCoordinates("1", "2", "0")).toBeNull();
    expect(parseTileCoordinates("1", "0", "-1")).toBeNull();
    expect(parseTileCoordinates("north", "0", "0")).toBeNull();
  });
});
